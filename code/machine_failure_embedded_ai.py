plt.plot(epochs, train_acc, label='Training Accuracy')
plt.plot(epochs, val_acc, label='Validation Accuracy')
plt.xlabel('Epochs')
plt.ylabel('Accuracy')
plt.title('Training vs Validation Accuracy (Balanced Dataset)')
plt.legend()

# Tracer l'évolution du learning rate
if lr_values:
    plt.subplot(2, 2, 3)
